export function resolveLanguage(search, stored, preferred = 'en') {
  const explicit = new URLSearchParams(search).get('lang')
  const normalize = value => /^zh(?:-|$)/i.test(value || '') ? 'zh' : /^en(?:-|$)/i.test(value || '') ? 'en' : null
  return normalize(explicit) || normalize(stored) || normalize(preferred) || 'en'
}
